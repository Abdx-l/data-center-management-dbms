CREATE TABLE rack (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR2(64) NOT NULL UNIQUE,
 capacity_units NUMBER(5) NOT NULL CHECK (capacity_units > 0)
);
CREATE TABLE server (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 hostname VARCHAR2(255) NOT NULL UNIQUE,
 rack_id NUMBER NOT NULL REFERENCES rack(id),
 start_unit NUMBER(5) NOT NULL CHECK (start_unit > 0),
 units NUMBER(5) NOT NULL CHECK (units > 0),
 watts NUMBER(9) NOT NULL CHECK (watts >= 0),
 status VARCHAR2(16) DEFAULT 'active' NOT NULL
   CHECK (status IN ('active','maintenance','retired'))
);
CREATE TABLE service (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR2(255) NOT NULL UNIQUE,
 server_id NUMBER NOT NULL REFERENCES server(id),
 owner VARCHAR2(255) NOT NULL
);
CREATE TABLE incident (
 id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 server_id NUMBER NOT NULL REFERENCES server(id),
 summary VARCHAR2(1000) NOT NULL,
 severity VARCHAR2(16) NOT NULL CHECK (severity IN ('low','medium','high')),
 opened_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 closed_at TIMESTAMP
);
CREATE INDEX idx_server_rack ON server(rack_id);
CREATE INDEX idx_incident_open ON incident(server_id, closed_at);

